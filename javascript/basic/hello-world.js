// Classic
console.log("Hello, World!");

// With variable
let helloWorld = "Hello, World!";

console.log(helloWorld);

// With variables and string concatenation
let hello = "Hello";
let world = "World";

console.log(hello + ", " + world + "!");

// With variables and template literals
let helloWorldTemplate = `${hello}, ${world}!`;

console.log(helloWorldTemplate);